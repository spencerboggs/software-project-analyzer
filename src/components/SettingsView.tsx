import { useEffect, useState } from 'react';
import type { CacheInfo, GitHubAuthStatus, Settings } from '../../shared/types';
import { FieldLabel } from './ui';

interface SettingsViewProps {
  settings: Settings;
  models: string[];
  ollama: { ok: boolean; error?: string };
  dataPath: string;
  ideaCount: number;
  folderCount: number;
  promptCount: number;
  github: GitHubAuthStatus;
  cache: CacheInfo;
  busy: boolean;
  onChange: (patch: Partial<Settings>) => void;
  onRefresh: (host: string) => void;
  onGithubConnect: (token: string) => Promise<boolean>;
  onGithubDisconnect: () => Promise<void>;
  onGithubRefresh: () => Promise<void>;
  onExportWorkspace: () => Promise<void>;
  onImportWorkspace: () => Promise<void>;
  onClearCache: () => Promise<CacheInfo>;
  onOpenExternal: (url: string) => void;
  onNotify: (kind: 'info' | 'error', text: string) => void;
}

const TOKEN_URL =
  'https://github.com/settings/tokens/new?description=Software%20Project%20Analyzer%20local%20search&scopes=';

function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(bytes < 10_240 ? 1 : 0)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}

export function SettingsView({
  settings,
  models,
  ollama,
  dataPath,
  ideaCount,
  folderCount,
  promptCount,
  github,
  cache,
  busy,
  onChange,
  onRefresh,
  onGithubConnect,
  onGithubDisconnect,
  onGithubRefresh,
  onExportWorkspace,
  onImportWorkspace,
  onClearCache,
  onOpenExternal,
  onNotify,
}: SettingsViewProps) {
  const [hostDraft, setHostDraft] = useState(settings.host);
  const [tokenDraft, setTokenDraft] = useState('');
  const [connecting, setConnecting] = useState(false);
  const [cacheInfo, setCacheInfo] = useState(cache);
  const [confirmCache, setConfirmCache] = useState(false);

  useEffect(() => {
    setHostDraft(settings.host);
  }, [settings.host]);

  useEffect(() => {
    setCacheInfo(cache);
  }, [cache]);

  useEffect(() => {
    let cancelled = false;
    void window.softwareProjectAnalyzer
      .cacheStats()
      .then((stats) => {
        if (!cancelled) setCacheInfo(stats);
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, []);

  useEffect(() => {
    if (!confirmCache) return;
    const timer = setTimeout(() => setConfirmCache(false), 3500);
    return () => clearTimeout(timer);
  }, [confirmCache]);

  const copy = async (value: string, label: string) => {
    try {
      await window.softwareProjectAnalyzer.copyText(value);
      onNotify('info', `${label} copied.`);
    } catch {
      onNotify('error', 'Could not access the clipboard.');
    }
  };

  const connect = async () => {
    if (!tokenDraft.trim() || connecting) return;
    setConnecting(true);
    const ok = await onGithubConnect(tokenDraft);
    setConnecting(false);
    if (ok) setTokenDraft('');
  };

  const clearCache = async () => {
    if (!confirmCache) {
      setConfirmCache(true);
      return;
    }
    const stats = await onClearCache();
    setCacheInfo(stats);
    setConfirmCache(false);
  };

  const resetLabel = github.resetAt
    ? new Date(github.resetAt).toLocaleTimeString(undefined, {
        hour: '2-digit',
        minute: '2-digit',
      })
    : '';

  return (
    <div className="view settings-view rise">
      <header className="view-head">
        <span className="eyebrow">03 / SETTINGS</span>
        <h1 className="display">Local by default.</h1>
        <p className="lede">
          Ideas are generated by a model running on this machine. Project scans use public search
          endpoints, but your workspace never leaves the app data folder.
        </p>
      </header>

      <div className="settings-grid">
        <section className="panel">
          <div className="panel-head">
            <span>OLLAMA</span>
            <span className={`status ${ollama.ok ? 'is-ok' : 'is-down'}`}>
              <span className="dot" aria-hidden="true" />
              {ollama.ok ? 'CONNECTED' : 'OFFLINE'}
            </span>
          </div>
          <div className="panel-body">
            <label className="field">
              <FieldLabel text="HOST" hint="where the local API listens" />
              <input
                value={hostDraft}
                placeholder="http://127.0.0.1:11434"
                onChange={(event) => setHostDraft(event.target.value)}
              />
            </label>

            <label className="field">
              <FieldLabel text="MODEL" hint="installed on this machine" />
              <select
                value={settings.model}
                onChange={(event) => onChange({ model: event.target.value })}
              >
                {models.length === 0 ? <option value="">No models found</option> : null}
                {models.map((model) => (
                  <option key={model} value={model}>
                    {model}
                  </option>
                ))}
              </select>
            </label>

            <div className="btn-row">
              <button type="button" className="btn" onClick={() => onRefresh(hostDraft)}>
                TEST &amp; REFRESH
              </button>
              <button
                type="button"
                className="btn ghost"
                onClick={() => void copy('ollama pull qwen3:8b', 'Pull command')}
              >
                COPY PULL COMMAND
              </button>
            </div>

            {ollama.error ? <p className="error-note">{ollama.error}</p> : null}

            <p className="fineprint">
              Recommended default: <code className="code">qwen3:8b</code> — balanced quality and
              speed on 8 GB of RAM or a 6 GB GPU. Install it with{' '}
              <code className="code">ollama pull qwen3:8b</code>. Smaller models are quicker but
              less careful at structured output; <code className="code">llama3.1:8b</code> is a
              dependable fallback.
            </p>
          </div>
        </section>

        <section className="panel">
          <div className="panel-head">
            <span>GITHUB ACCESS</span>
            <span className={`status ${github.connected ? 'is-ok' : 'is-down'}`}>
              <span className="dot" aria-hidden="true" />
              {github.connected ? `@${github.login}` : 'ANONYMOUS'}
            </span>
          </div>
          <div className="panel-body">
            <p className="fineprint">
              Anonymous GitHub search allows 10 requests per minute and 3 queries per scan. A token
              raises that to 30 per minute and 10 queries per scan.
            </p>

            {github.connected ? (
              <>
                <div className="meta-list">
                  <div className="meta-row">
                    <span>ACCOUNT</span>
                    <span className="meta-value">@{github.login}</span>
                  </div>
                  <div className="meta-row">
                    <span>SEARCH LIMIT</span>
                    <span className="meta-value">{github.limit} / MIN</span>
                  </div>
                  <div className="meta-row">
                    <span>QUERIES PER SCAN</span>
                    <span className="meta-value">{github.queriesPerScan}</span>
                  </div>
                  {typeof github.remaining === 'number' ? (
                    <div className="meta-row">
                      <span>REMAINING</span>
                      <span className="meta-value">
                        {github.remaining} / MIN{resetLabel ? ` · RESET ${resetLabel}` : ''}
                      </span>
                    </div>
                  ) : null}
                </div>

                {github.error ? <p className="error-note">{github.error}</p> : null}

                <div className="btn-row">
                  <button
                    type="button"
                    className="btn"
                    onClick={() => void onGithubRefresh()}
                    disabled={busy}
                  >
                    CHECK LIMIT
                  </button>
                  <button
                    type="button"
                    className="btn ghost"
                    onClick={() => void onGithubDisconnect()}
                    disabled={busy}
                  >
                    DISCONNECT
                  </button>
                </div>
              </>
            ) : (
              <>
                <label className="field">
                  <FieldLabel text="PERSONAL ACCESS TOKEN" hint="stored encrypted on this PC" />
                  <input
                    type="password"
                    value={tokenDraft}
                    placeholder="ghp_… or github_pat_…"
                    autoComplete="off"
                    spellCheck={false}
                    onChange={(event) => setTokenDraft(event.target.value)}
                  />
                </label>
                <div className="btn-row">
                  <button
                    type="button"
                    className="btn primary"
                    onClick={() => void connect()}
                    disabled={busy || connecting || !tokenDraft.trim()}
                  >
                    {connecting ? 'CHECKING…' : 'CONNECT TOKEN'}
                  </button>
                  <button
                    type="button"
                    className="btn ghost"
                    onClick={() => onOpenExternal(TOKEN_URL)}
                  >
                    CREATE TOKEN ↗
                  </button>
                </div>
                <p className="fineprint">
                  No scopes are required for public repository search. A classic token with no boxes
                  checked is enough. The scan still works without one.
                </p>
              </>
            )}

            <p className="fineprint">
              The token is encrypted with the operating system&apos;s secure storage, kept outside
              the workspace, and never included in backups.
            </p>
          </div>
        </section>

        <section className="panel">
          <div className="panel-head">
            <span>WORKSPACE DATA</span>
            <span className="panel-meta">PLAIN JSON</span>
          </div>
          <div className="panel-body">
            <div className="meta-list">
              <div className="meta-row">
                <span>IDEAS</span>
                <span className="meta-value">{ideaCount}</span>
              </div>
              <div className="meta-row">
                <span>FOLDERS</span>
                <span className="meta-value">{folderCount}</span>
              </div>
              <div className="meta-row">
                <span>SAVED BRIEFS</span>
                <span className="meta-value">{promptCount}</span>
              </div>
              <div className="meta-row">
                <span>RESEARCH CACHE</span>
                <span className="meta-value">{cacheInfo.entries} ENTRIES</span>
              </div>
              <div className="meta-row">
                <span>CACHE SIZE</span>
                <span className="meta-value">{formatBytes(cacheInfo.bytes)}</span>
              </div>
            </div>
            <div className="btn-row">
              <button
                type="button"
                className="btn primary"
                onClick={() => void onExportWorkspace()}
                disabled={busy}
              >
                EXPORT BACKUP
              </button>
              <button
                type="button"
                className="btn ghost"
                onClick={() => void onImportWorkspace()}
                disabled={busy}
              >
                IMPORT BACKUP
              </button>
            </div>
            <label className="field">
              <FieldLabel text="FILE LOCATION" hint="back this up to keep your workspace" />
              <input
                value={dataPath}
                readOnly
                title={dataPath}
                onFocus={(event) => event.target.select()}
              />
            </label>
            <div className="btn-row">
              <button
                type="button"
                className="btn ghost"
                onClick={() => void copy(dataPath, 'Data path')}
              >
                COPY PATH
              </button>
              <button
                type="button"
                className="btn ghost"
                onClick={() => void clearCache()}
                disabled={busy || cacheInfo.entries === 0}
              >
                {confirmCache ? 'SURE? CLEAR CACHE' : 'CLEAR RESEARCH CACHE'}
              </button>
            </div>
            <p className="fineprint">
              Backups contain ideas, folders, and saved briefs. The GitHub token and research cache
              are deliberately excluded. Changes are written locally after a short delay.
            </p>
          </div>
        </section>

        <section className="panel">
          <div className="panel-head">
            <span>ABOUT SCANS</span>
            <span className="panel-meta">V1.0.0</span>
          </div>
          <div className="panel-body">
            <ul className="about-list">
              <li>
                <strong>GitHub</strong>
                <span>
                  {github.connected
                    ? `Authenticated as @${github.login}: 30 search requests per minute, up to 10 queries per scan.`
                    : 'Anonymous: 10 search requests per minute, up to 3 queries per scan. Connect a token above to raise both.'}
                </span>
              </li>
              <li>
                <strong>Web &amp; Hacker News</strong>
                <span>
                  General results come from DuckDuckGo&apos;s HTML endpoint and story search from
                  Algolia&apos;s Hacker News API. Neither needs a key.
                </span>
              </li>
              <li>
                <strong>Cache</strong>
                <span>
                  Search responses are reused for 6–12 hours, model grades for 7 days, and READMEs
                  for 7 days. Re-scanning an existing idea forces a fresh pass.
                </span>
              </li>
              <li>
                <strong>Estimates</strong>
                <span>
                  Completeness grades are the model&apos;s read of real evidence. Usage uses stars,
                  forks, owner type and points. Treat both as estimates, not facts.
                </span>
              </li>
              <li>
                <strong>Privacy</strong>
                <span>
                  Prompts and ideas are sent only to your local Ollama model. Only short search
                  queries leave this machine during a scan.
                </span>
              </li>
            </ul>
          </div>
        </section>

        <section className="panel is-disabled" aria-disabled="true">
          <div className="panel-head">
            <span>CLOUD MODELS</span>
            <span className="stamp">NOT IMPLEMENTED YET</span>
          </div>
          <div className="panel-body">
            <p className="fineprint">
              Placeholder only. This build runs entirely on your local Ollama instance. A cloud
              model option is not wired up yet, and no key is stored.
            </p>
            <label className="field">
              <FieldLabel text="OPENAI API KEY" hint="disabled in this build" />
              <input type="password" value="" placeholder="sk-…" readOnly disabled />
            </label>
            <label className="field">
              <FieldLabel text="MODEL ID" hint="example only" />
              <input value="gpt-4.1-mini" readOnly disabled />
            </label>
            <button type="button" className="btn" disabled>
              SAVE KEY
            </button>
          </div>
        </section>
      </div>
    </div>
  );
}
